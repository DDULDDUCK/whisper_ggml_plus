#!/bin/bash

# Script to generate the embedded Metal source file
# This merges ggml-common.h and ggml-metal-impl.h into ggml-metal.metal

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IOS_DIR="$(dirname "$SCRIPT_DIR")"
AUTOGEN_DIR="$IOS_DIR/autogenerated"
CLASSES_DIR="$IOS_DIR/whisper_ggml_plus/Classes"

METAL_SOURCE="$CLASSES_DIR/whisper/ggml/src/ggml-metal/ggml-metal.metal"
METAL_IMPL="$CLASSES_DIR/whisper/ggml/src/ggml-metal/ggml-metal-impl.h"
GGML_COMMON="$CLASSES_DIR/whisper/ggml/src/ggml-common.h"

METAL_EMBED_TMP="$AUTOGEN_DIR/ggml-metal-embed.metal.tmp"
METAL_EMBED="$AUTOGEN_DIR/ggml-metal-embed.metal"

# Create autogenerated directory if it doesn't exist
mkdir -p "$AUTOGEN_DIR"

echo "Generating embedded Metal source..."
echo "  Metal source: $METAL_SOURCE"
echo "  Common header: $GGML_COMMON"
echo "  Implementation header: $METAL_IMPL"
echo "  Output: $METAL_EMBED"

# Emit a self-contained shader for both the legacy precompiler and SwiftPM's
# runtime compilation. No SDK-specific metallib is shared with the simulator.
python3 - "$METAL_SOURCE" "$GGML_COMMON" "$METAL_IMPL" "$METAL_EMBED" "$IOS_DIR/whisper_ggml_plus/Resources/ggml-metal.metal" <<'PYSHADER'
from pathlib import Path
import sys
source, common, impl, *outputs = map(Path, sys.argv[1:])
shader = source.read_text().replace(
    '#if defined(GGML_METAL_EMBED_LIBRARY)\n__embed_ggml-common.h__\n#else\n#include "ggml-common.h"\n#endif',
    common.read_text(),
).replace('#include "ggml-metal-impl.h"', impl.read_text())
for output in outputs:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(shader)
PYSHADER

echo "Generated self-contained Metal source: $METAL_EMBED"
